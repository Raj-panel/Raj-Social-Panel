// ==========================================
// GENERATE PAYMENT ORDER
// ==========================================

function generateOrder() {

    const link =
        document
            .getElementById(
                "link"
            )
            .value
            .trim();


    if (!selectedPackage) {

        alert(
            "Please select a package first!"
        );

        return;
    }


    if (!link) {

        alert(
            "Please enter target link or username!"
        );

        return;
    }


    const totalPrice =
        Number(
            selectedPackage.price
        ).toFixed(2);


    const upiId =
        "Saheb.68@ptyes";


    const payeeName =
        "Raj Social Panel";


    const upiUrl =
        `upi://pay?pa=${upiId}` +
        `&pn=${encodeURIComponent(
            payeeName
        )}` +
        `&am=${totalPrice}` +
        `&cu=INR`;


    document.getElementById(
        "qrCodeImg"
    ).src =
        `https://api.qrserver.com/v1/create-qr-code/` +
        `?size=250x250` +
        `&data=${encodeURIComponent(
            upiUrl
        )}`;


    // ==========================================
    // BINANCE CONVERSION
    // ==========================================

    const usdtAmount =
        (
            selectedPackage.price /
            96
        ).toFixed(2);


    const usdtDisplay =
        document.getElementById(
            "usdtAmountDisplay"
        );


    if (
        usdtDisplay
    ) {

        usdtDisplay.innerText =
            `$${usdtAmount} USDT`;

    }


    document.getElementById(
        "paymentCard"
    ).style.display =
        "block";


    switchPaymentMethod(
        "upi"
    );


    document.getElementById(
        "paymentCard"
    ).scrollIntoView({
        behavior: "smooth"
    });
}


