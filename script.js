        `*Quantity:* ${selectedPackage.quantity}%0A` +

        `*Target Link:* ${link}%0A` +

        `*Amount Paid:* ${amountText}%0A` +

        `*Payment Mode:* ${currentPaymentMethod.toUpperCase()}%0A` +

        `*Transaction ID/UTR:* ${utr}%0A%0A` +

        `Please start processing my order!`;

