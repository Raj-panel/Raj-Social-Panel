// ==========================================
// CUSTOM PRICE
// ==========================================

function calculateCustomPrice(
    serviceName,
    ratePer1000,
    providerId
) {

    const qty =
        parseInt(
            document.getElementById(
                "customQtyInput"
            ).value
        ) || 0;


    const priceDisplay =
        document.getElementById(
            "customPriceDisplay"
        );


    if (qty > 0) {

        const total =
            (
                qty /
                1000
            ) *
            ratePer1000;


        priceDisplay.innerText =
            `Total: ₹${total.toFixed(2)} INR`;


        selectedPackage = {

            name:
                `${qty} ${serviceName}`,

            price:
                total,

            providerId:
                providerId,

            quantity:
                qty,

            category:
                currentCategory

        };


        showCheckoutSummary(
            `${qty} ${serviceName}`,
            total.toFixed(2)
        );

    } else {

        priceDisplay.innerText =
            "Total: ₹0.00 INR";


        document.getElementById(
            "checkoutSection"
        ).style.display =
            "none";


        selectedPackage =
            null;
    }
}


// ==========================================
// SELECT NORMAL PACKAGE
// ==========================================

function selectPackageCard(
    cardElement,
    pkgData
) {

    document
        .querySelectorAll(
            ".pkg-card"
        )
        .forEach(
            c =>
                c.classList.remove(
                    "selected"
                )
        );


    cardElement.classList.add(
        "selected"
    );


    const quantity =
        extractQuantity(
            pkgData.name
        );


    selectedPackage = {

        ...pkgData,

        category:
            currentCategory,

        quantity:
            quantity

    };


    showCheckoutSummary(
        pkgData.name,
        Number(
            pkgData.price
        ).toFixed(2)
    );
}


// ==========================================
// EXTRACT QUANTITY
// ==========================================

function extractQuantity(
    name
) {

    const text =
        name
            .toUpperCase()
            .replace(
                /,/g,
                ""
            );


    const match =
        text.match(
            /(\d+(?:\.\d+)?)\s*(M|K)?/
        );


    if (!match) {

        return 0;

    }


    let number =
        parseFloat(
            match[1]
        );


    const unit =
        match[2];


    if (
        unit === "K"
    ) {

        number =
            number *
            1000;

    }

    else if (
        unit === "M"
    ) {

        number =
            number *
            1000000;

    }


    return Math.floor(
        number
    );
}


